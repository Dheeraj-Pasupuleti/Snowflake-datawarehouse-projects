CREATE OR REPLACE TASK DAILY_SALES_LOAD
WAREHOUSE = ENTERPRISE_WH
SCHEDULE = 'USING CRON 0 0 * * * UTC'
AS
MERGE INTO SALES AS target
USING SALES_STAGING AS source
ON target.SALE_ID = source.SALE_ID

WHEN NOT MATCHED THEN
    INSERT (
        SALE_ID,
        CUSTOMER_ID,
        PRODUCT_ID,
        BRANCH_ID,
        QUANTITY,
        SALE_DATE,
        TOTAL_AMOUNT
    )
    VALUES (
        source.SALE_ID,
        source.CUSTOMER_ID,
        source.PRODUCT_ID,
        source.BRANCH_ID,
        source.QUANTITY,
        source.SALE_DATE,
        source.TOTAL_AMOUNT
    );

ALTER TASK DAILY_SALES_LOAD RESUME;

SHOW TASKS;

SELECT *
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY())
WHERE NAME = 'DAILY_SALES_LOAD'
ORDER BY SCHEDULED_TIME DESC;

SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    SUM(s.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM CUSTOMERS c
JOIN SALES s
    ON c.CUSTOMER_ID = s.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME
ORDER BY TOTAL_REVENUE DESC;


SELECT
    b.BRANCH_ID,
    b.BRANCH_NAME,
    SUM(s.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM BRANCHES b
JOIN SALES s
    ON b.BRANCH_ID = s.BRANCH_ID
GROUP BY
    b.BRANCH_ID,
    b.BRANCH_NAME
ORDER BY TOTAL_REVENUE DESC;

SELECT
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    SUM(s.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM PRODUCTS p
JOIN SALES s
    ON p.PRODUCT_ID = s.PRODUCT_ID
GROUP BY
    p.PRODUCT_ID,
    p.PRODUCT_NAME
ORDER BY TOTAL_REVENUE DESC;

SELECT
    DATE_TRUNC('MONTH', SALE_DATE) AS MONTH,
    SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM SALES
GROUP BY DATE_TRUNC('MONTH', SALE_DATE)
ORDER BY MONTH;


-- PHASE 30: COMPLETE STAR SCHEMA VIEW

CREATE OR REPLACE VIEW VW_RETAIL_SALES AS
SELECT
    f.SALE_ID,

    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.CITY AS CUSTOMER_CITY,
    c.STATE AS CUSTOMER_STATE,
    c.MEMBERSHIP,

    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.CATEGORY,
    p.BRAND,
    p.PRICE,

    b.BRANCH_ID,
    b.BRANCH_NAME,
    b.CITY AS BRANCH_CITY,
    b.STATE AS BRANCH_STATE,
    b.REGION,
    b.MANAGER_NAME,

    d.DATE_ID,
    d.DATE,
    d.DAY,
    d.DAY_NAME,
    d.WEEK_NO,
    d.MONTH,
    d.QUARTER,
    d.YEAR,
    d.IS_WEEKEND,

    f.QUANTITY,
    f.TOTAL_AMOUNT

FROM FACT_SALES f

JOIN DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID

JOIN DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID

JOIN DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID

JOIN DIM_DATE d
    ON f.DATE_ID = d.DATE_ID;



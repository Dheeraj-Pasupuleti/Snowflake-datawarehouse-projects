-- PHASE 19: MONTHLY REVENUE

SELECT
    d.YEAR,
    d.MONTH,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_DATE d
    ON f.DATE_ID = d.DATE_ID
GROUP BY
    d.YEAR,
    d.MONTH
ORDER BY
    d.YEAR,
    MIN(d.DATE_ID);



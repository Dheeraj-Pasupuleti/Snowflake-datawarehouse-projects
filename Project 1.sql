CREATE OR REPLACE TABLE CUSTOMERS (
    CUSTOMER_ID INT,
    FIRST_NAME STRING,
    LAST_NAME STRING,
    EMAIL STRING,
    PHONE STRING,
    ADDRESS STRING
);

CREATE OR REPLACE TABLE FOODITEMS (
    FOOD_ID INT,
    NAME STRING,
    PRICE NUMBER(10,2),
    CATEGORY STRING,
    AVAILABILITY STRING
);

CREATE OR REPLACE TABLE ORDERS (
    ORDER_ID INT,
    CUSTOMER_ID INT,
    FOOD_ID INT,
    QUANTITY INT,
    ORDER_DATE TIMESTAMP,
    STATUS STRING,
    TOTAL_AMOUNT NUMBER(10,2)
);


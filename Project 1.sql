SELECT
    c.CUSTOMER_ID,
    CONCAT(c.FIRST_NAME, ' ', c.LAST_NAME) AS CUSTOMER_NAME,
    SUM(o.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS c
JOIN ORDERS o
    ON c.CUSTOMER_ID = o.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME
ORDER BY c.CUSTOMER_ID;




SELECT
    c.CUSTOMER_ID,
    CONCAT(c.FIRST_NAME, ' ', c.LAST_NAME) AS CUSTOMER_NAME,
    SUM(o.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS c
JOIN ORDERS o
    ON c.CUSTOMER_ID = o.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME
ORDER BY TOTAL_SPENT DESC
LIMIT 1;


SELECT SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM ORDERS;


SELECT
    f.CATEGORY,
    SUM(o.TOTAL_AMOUNT) AS REVENUE
FROM FOODITEMS f
JOIN ORDERS o
    ON f.FOOD_ID = o.FOOD_ID
GROUP BY f.CATEGORY
ORDER BY REVENUE DESC;


SELECT
    STATUS,
    SUM(TOTAL_AMOUNT) AS REVENUE
FROM ORDERS
GROUP BY STATUS
ORDER BY REVENUE DESC;


SELECT
    c.CUSTOMER_ID,
    CONCAT(c.FIRST_NAME, ' ', c.LAST_NAME) AS CUSTOMER_NAME,
    SUM(o.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS c
JOIN ORDERS o
    ON c.CUSTOMER_ID = o.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME
ORDER BY TOTAL_SPENT DESC
LIMIT 3;



SELECT
    c.CUSTOMER_ID,
    CONCAT(c.FIRST_NAME, ' ', c.LAST_NAME) AS CUSTOMER_NAME,
    COUNT(o.ORDER_ID) AS ORDERS_PLACED
FROM CUSTOMERS c
JOIN ORDERS o
    ON c.CUSTOMER_ID = o.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME
ORDER BY ORDERS_PLACED DESC;


SELECT *
FROM ORDERS
WHERE STATUS = 'Delivered';


SELECT
    o.ORDER_ID,
    CONCAT(c.FIRST_NAME, ' ', c.LAST_NAME) AS CUSTOMER_NAME,
    o.ORDER_DATE,
    o.STATUS,
    o.TOTAL_AMOUNT
FROM ORDERS o
JOIN CUSTOMERS c
    ON o.CUSTOMER_ID = c.CUSTOMER_ID
WHERE o.ORDER_DATE > '2026-07-12'
ORDER BY o.ORDER_DATE;


CREATE OR REPLACE VIEW CUSTOMER_SALES_REPORT AS
SELECT
    c.CUSTOMER_ID,
    CONCAT(c.FIRST_NAME, ' ', c.LAST_NAME) AS CUSTOMER_NAME,
    SUM(o.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS c
JOIN ORDERS o
    ON c.CUSTOMER_ID = o.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME;

SELECT * FROM CUSTOMER_SALES_REPORT;



SELECT *
FROM CUSTOMER_SALES_REPORT
ORDER BY TOTAL_SPENT DESC;


    
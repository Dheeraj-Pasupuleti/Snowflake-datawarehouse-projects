-- task 16
WITH PRODUCT_REVENUE AS (
    SELECT p.PRODUCT_ID, p.PRODUCT_NAME, p.CATEGORY, SUM(s.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM PRODUCTS p
    JOIN SALES s ON p.PRODUCT_ID = s.PRODUCT_ID
    GROUP BY p.PRODUCT_ID, p.PRODUCT_NAME, p.CATEGORY
),

RANKED_PRODUCTS AS (
    SELECT PRODUCT_ID, PRODUCT_NAME, CATEGORY, TOTAL_REVENUE,
        ROW_NUMBER() OVER (
            PARTITION BY CATEGORY
            ORDER BY TOTAL_REVENUE DESC
        ) AS RN FROM PRODUCT_REVENUE
)

SELECT PRODUCT_ID, PRODUCT_NAME, CATEGORY, TOTAL_REVENUE FROM RANKED_PRODUCTS
WHERE RN = 1;


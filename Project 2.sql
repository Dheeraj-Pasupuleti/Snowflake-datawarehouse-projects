-- Task 20 CTE
WITH CUSTOMER_REVENUE AS (
    SELECT c.CUSTOMER_ID, c.CUSTOMER_NAME, SUM(s.TOTAL_AMOUNT) AS TOTAL_SPENDING
    FROM CUSTOMERS c
    JOIN SALES s ON c.CUSTOMER_ID = s.CUSTOMER_ID
    GROUP BY c.CUSTOMER_ID, c.CUSTOMER_NAME
),

AVERAGE_SPENDING AS (
    SELECT AVG(TOTAL_SPENDING) AS AVG_SPENDING FROM CUSTOMER_REVENUE
)

SELECT cr.CUSTOMER_ID, cr.CUSTOMER_NAME, cr.TOTAL_SPENDING FROM CUSTOMER_REVENUE cr
CROSS JOIN AVERAGE_SPENDING av
WHERE cr.TOTAL_SPENDING > av.AVG_SPENDING
ORDER BY cr.TOTAL_SPENDING DESC;

